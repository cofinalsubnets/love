# test/gate/cclib.sh -- the C gates' shared helpers, dotted after skip.sh.
# fail reads $name; moonrun runs love $m's mooncc, moonc the one in $ho
fail() { echo "FAIL $name: $*" >&2; exit 1; }
moonrun() { LOVE_NO_IMAGE= "$m" mooncc "$@"; }
moonc() { LOVE_NO_IMAGE= "$ho/love" mooncc "$@"; }
have() { command -v "$1" > /dev/null 2>&1; }
# refusal ST LOG SRC: mooncc's refusal of SRC exited ST, not a signal, and LOG names SRC
refusal() {
  [ "$1" -lt 128 ] || fail "$3: mooncc died on a signal ($1) where a refusal was expected"
  grep -q "$3" "$2" || { cat "$2" >&2; fail "$3: the refusal does not name the file"; }
}
# refused LOG SRC ARGS..: mooncc ARGS must refuse SRC
refused() {
  _l=$1 _s=$2; shift 2
  moonrun "$@" > "$_l" 2>&1 && fail "$_s: mooncc $* BUILT a program listed as refused -- take it off the list"
  refusal $? "$_l" "$_s"
}
# hdrnames: every function moonlibc's headers declare, one per line, sorted. a declaration
# starts with a lowercase type word and may chain, `int a(x), b(y);`, over lines ending in a
# comma; each declarator at paren depth 0 names what precedes its first paren
hdr=src/apps/moon/include
hdrs() { (cd "$hdr" && ls *.h sys/*.h); }
hdrnames() {
  for h in $(hdrs); do awk '
  function one(p) { if (!index(p, "(")) return; sub(/\(.*/, "", p); sub(/.*[ *]/, "", p)
                    if (p ~ /^[a-z_][a-z_0-9]*$/) print p }
  function each(s,  i, c, d, p) { d = 0; p = ""
    for (i = 1; i <= length(s); i++) { c = substr(s, i, 1)
      if (c == "(") d++; else if (c == ")") d--
      if (c == "," && !d) { one(p); p = "" } else p = p c }
    one(p) }
  more { acc = acc " " $0; if ($0 !~ /,[ \t]*$/) { more = 0; each(acc) }; next }
  /^[a-z][a-zA-Z_0-9 ]*[ *][a-z_][a-z_0-9]*\(/ && !/^(typedef|return|static) / {
    acc = $0; sub(/;.*/, "", acc); if ($0 ~ /,[ \t]*$/) more = 1; else each(acc) }' "$hdr/$h"; done | sort -u
}
# hdrdecls NAME..: one program including every header and taking each name's address
hdrdecls() {
  echo '/* generated by test/gate/cclib.sh -- do not edit */'
  for h in $(hdrs); do echo "#include <$h>"; done
  echo 'void *const __refs[] = {'
  for nm in "$@"; do echo "  (void *) $nm,"; done
  echo '  0 };'
  echo 'int main(void) { return __refs[0] == (void *) 1 ? 1 : 0; }'
}
